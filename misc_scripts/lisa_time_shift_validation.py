warnings.filterwarnings("ignore", category=FutureWarning)

import numpy as np

PROJECT = "/work/pi_mpuerrer_uri_edu/projects/LISA_npe"
DEFAULT_MODEL = f"{PROJECT}/cpu_12_wk_thin8/model_latest.pt"
DEFAULT_OUTDIR = f"{PROJECT}/lisa_time_shift_validation"

# Tolerances. The new and old signal paths differ only by float64 round-off
# (the spline of phase + 2 pi f Deltat is the spline of phase plus the exact
# linear term, and t0 + Deltat is the same orbital time), so these are loose.
TOL_MISMATCH = 1e-9
TOL_REL_MAX = 1e-5
TOL_TL_FORMULA = 5e-8   # s; lisabeta's reference subtracts two ~5e7 s numbers
TOL_TSSB_EXPLICIT = 1e-4  # s; lisabeta's explicit inverse is 2nd order
TOL_ROUND_TRIP = 1e-9   # s
TOL_RESPONSE_DELAY = 1e-5  # s


def build_parser():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model", default=DEFAULT_MODEL, help="Model whose metadata defines domain, prior, lisa_settings.")
    ap.add_argument("--injection-script-dir", default=PROJECT,
                    help="Directory holding lisa_injection_inference.py (prior draw + naming adapters).")
    ap.add_argument("--n-draws", type=int, default=6, help="Random intrinsic/sky draws for the signal checks.")
    ap.add_argument("--shifts", default="-1800,-150,37.5,150,1800", help="Time offsets (s) to test.")
    ap.add_argument("--asd-index", type=int, default=0)
    ap.add_argument("--seed", type=int, default=20261113)
    ap.add_argument("--outdir", default=DEFAULT_OUTDIR)
    return ap


class Report:
    def __init__(self):
        self.checks = []

    def add(self, name, value, threshold, passed, **info):
        self.checks.append({"name": name, "value": float(value), "threshold": float(threshold),
                            "passed": bool(passed), **info})
        flag = "PASS" if passed else "FAIL"
        extra = " ".join(f"{k}={v}" for k, v in info.items())
        print(f"[{flag}] {name}: {value:.3e} (threshold {threshold:.1e}) {extra}", flush=True)

    @property
    def all_passed(self):
        return all(c["passed"] for c in self.checks)


def provenance():
    import dingo
    import lisabeta

    dingo_dir = os.path.dirname(os.path.dirname(os.path.abspath(dingo.__file__)))

    def git(*args):
        try:
            return subprocess.check_output(["git", "-C", dingo_dir, *args], text=True,
                                           stderr=subprocess.DEVNULL).strip()
        except Exception:
            return None

    return {
        "dingo_file": dingo.__file__,
        "dingo_commit": git("rev-parse", "HEAD"),
        "dingo_branch": git("rev-parse", "--abbrev-ref", "HEAD"),
        "dingo_dirty": bool(git("status", "--porcelain", "--untracked-files=no")),
        "lisabeta_file": lisabeta.__file__,
        "python": sys.version.split()[0],
        "slurm_job_id": os.environ.get("SLURM_JOB_ID"),
    }


def whitened_metrics(a: dict, b: dict, min_idx: int):
    """Mismatch and max relative difference over all channels (whitened strains)."""
    aa = bb = ab = 0.0
    max_diff = max_ref = 0.0
    for k in b:
        x = np.asarray(a[k])[..., min_idx:]
        y = np.asarray(b[k])[..., min_idx:]
        aa += np.sum(np.abs(x) ** 2)
        bb += np.sum(np.abs(y) ** 2)
        ab += np.sum(np.conj(x) * y).real
        max_diff = max(max_diff, np.max(np.abs(x - y)))
        max_ref = max(max_ref, np.max(np.abs(y)))
    mismatch = 1.0 - ab / np.sqrt(aa * bb)
    return float(mismatch), float(max_diff / max_ref)


def reference_signal(inj, theta: dict):
    """Old path: lisabeta generates the modes with Deltat baked in; the projection
    applies no time shift. Mirrors Injection.signal otherwise."""
    import lisabeta.tools.pytools as pytools
    from dingo.gw.prior import split_off_extrinsic_parameters

    ti, te = split_off_extrinsic_parameters(theta)
    ti = {k: float(v) for k, v in ti.items()}
    deltat = float(te.pop("Deltat", 0.0))
    if te.pop("DeltatL", None) is not None:
        raise ValueError("reference_signal takes Deltat, not DeltatL")
    ti = pytools.complete_mass_params(ti)
    ti = pytools.complete_spin_params(ti)
    ti["Deltat"] = deltat
    pols = inj.waveform_generator.generate_amp_phase({**te, **ti})
    sample = {"parameters": ti, "extrinsic_parameters": te, "waveform": pols}
    if inj.asd is not None:
        sample["asds"] = inj.asd
    return inj.projection_transforms(sample)["waveform"]


def check_constants(report):
    import lisabeta.pyconstants as pc
    from dingo.gw import lisa_time as lt

    worst = 0.0
    for ours, theirs in [(lt.C_SI, pc.C_SI), (lt.AU_SI, pc.AU_SI), (lt.YRSID_SI, pc.YRSID_SI),
                         (lt.EARTH_ORBIT_OMEGA_SI, pc.EarthOrbitOmega_SI)]:
        worst = max(worst, abs(ours - theirs) / abs(theirs))
    report.add("constants_rel_diff", worst, 1e-15, worst <= 1e-15)


def check_conversions(report, rng, t0_s, lisaconst):
    import lisabeta.lisa.lisatools as lisatools
    import lisabeta.lisa.pyresponse as pyresponse
    from dingo.gw import lisa_time as lt

    const = pyresponse.LISAconstDict[lisaconst] if isinstance(lisaconst, str) else lisaconst
    ok_const = const["OrbitPhi0"] == 0.0 and const["Orbitt0"] == 0.0
    report.add("lisaconst_phase_origin_zero", 0.0 if ok_const else 1.0, 0.0, ok_const,
               OrbitPhi0=const["OrbitPhi0"], Orbitt0=const["Orbitt0"])

    n = 5000
    lam = rng.uniform(-np.pi, np.pi, n)
    bet = np.arcsin(rng.uniform(-1, 1, n))
    dt = rng.uniform(-1800, 1800, n)
    for frozen in (False, True):
        tag = "frozen" if frozen else "moving"
        ours = lt.deltatL_from_deltat(dt, lam, bet, t0_s, frozen_lisa=frozen)
        ref = lisatools.tLfromSSBframe(t0_s + dt, lam, bet, frozenLISA=frozen, tfrozenLISA=t0_s) - t0_s
        err = np.max(np.abs(ours - ref))
        report.add(f"tL_vs_lisatools_{tag}", err, TOL_TL_FORMULA, err <= TOL_TL_FORMULA)

        dtL = ours
        inv = lt.deltat_from_deltatL(dtL, lam, bet, t0_s, frozen_lisa=frozen)
        ref_inv = lisatools.tSSBfromLframe(t0_s + dtL, lam, bet, frozenLISA=frozen, tfrozenLISA=t0_s) - t0_s
        err = np.max(np.abs(inv - ref_inv))
        report.add(f"tSSB_vs_lisatools_{tag}", err, TOL_TSSB_EXPLICIT, err <= TOL_TSSB_EXPLICIT)
        err = np.max(np.abs(inv - dt))
        report.add(f"round_trip_{tag}", err, TOL_ROUND_TRIP, err <= TOL_ROUND_TRIP)


def check_response_delay(report, rng, t0_s, lisa_settings):
    """phaseRdelay from lisabeta's response is 2 pi f x (t_L - t_SSB) at the time t."""
    import lisabeta.lisa.pyresponse as pyresponse
    import lisabeta.pyconstants as pc
    from dingo.gw import lisa_time as lt

    freqs = np.array([1e-4, 1e-3, 5e-3, 2e-2])
    worst = 0.0
    for _ in range(300):
        lam = rng.uniform(-np.pi, np.pi)
        bet = np.arcsin(rng.uniform(-1, 1))
        dt = rng.uniform(-1800, 1800)
        tf = np.full(len(freqs), dt)  # t(f) = Deltat -> response evaluated at t0_s + Deltat
        resp = pyresponse.LISAFDresponseTDI3Chan(
            freqs, tf, t0_s / pc.YRSID_SI, 2, 2, 0.6, 0.0, lam, bet, 0.3,
            "TDIAET", lisa_settings["LISAconst"], "full", False, lisa_settings["TDIrescaled"],
        )
        phaseRdelay = np.asarray(resp.get_response()[0])
        implied = dt + phaseRdelay / (2 * np.pi * freqs)
        ours = lt.deltatL_from_deltat(dt, lam, bet, t0_s)
        worst = max(worst, np.max(np.abs(implied - ours)))
    report.add("response_delay_equals_DeltatL", worst, TOL_RESPONSE_DELAY, worst <= TOL_RESPONSE_DELAY)


def make_injection(metadata, asd, frozen):
    import dingo.gw.injection as injection

    md = copy.deepcopy(metadata)
    md["train_settings"]["data"]["lisa_settings"]["frozenLISA"] = frozen
    inj = injection.Injection.from_posterior_model_metadata(md)
    inj.asd = asd
    inj.whiten = True
    return inj


def check_signals(report, inj, draws, shifts, frozen, t0_key="geocent_time"):
    from dingo.gw import lisa_time as lt

    tag = "frozen" if frozen else "moving"
    min_idx = inj.data_domain.min_idx
    worst = {"ssb_mm": 0.0, "ssb_rel": 0.0, "l_mm": 0.0, "l_rel": 0.0}
    min_shift_mismatch = np.inf
    for theta in draws:
        base = dict(theta, Deltat=0.0)
        unshifted = inj.signal(base)["waveform"]
        for s in shifts:
            # (4) SSB-frame offset
            new = inj.signal(dict(theta, Deltat=s))["waveform"]
            ref = reference_signal(inj, dict(theta, Deltat=s))
            mm, rel = whitened_metrics(new, ref, min_idx)
            worst["ssb_mm"] = max(worst["ssb_mm"], abs(mm))
            worst["ssb_rel"] = max(worst["ssb_rel"], rel)
            # (6) the shift does something (round-off level would be ~1e-12)
            if abs(s) >= 150:
                mm_shift, _ = whitened_metrics(new, unshifted, min_idx)
                min_shift_mismatch = min(min_shift_mismatch, mm_shift)
            # (5) LISA-frame offset, against the old path at the converted Deltat
            new_l = inj.signal(dict(theta, Deltat=0.0, DeltatL=s))["waveform"]
            dt_conv = lt.deltat_from_deltatL(s, theta["lambda"], theta["beta"],
                                             theta[t0_key], frozen_lisa=frozen)
            ref_l = reference_signal(inj, dict(theta, Deltat=dt_conv))
            mm, rel = whitened_metrics(new_l, ref_l, min_idx)
            worst["l_mm"] = max(worst["l_mm"], abs(mm))
            worst["l_rel"] = max(worst["l_rel"], rel)
    report.add(f"signal_ssb_mismatch_{tag}", worst["ssb_mm"], TOL_MISMATCH, worst["ssb_mm"] <= TOL_MISMATCH)
    report.add(f"signal_ssb_rel_max_{tag}", worst["ssb_rel"], TOL_REL_MAX, worst["ssb_rel"] <= TOL_REL_MAX)
    report.add(f"signal_lframe_mismatch_{tag}", worst["l_mm"], TOL_MISMATCH, worst["l_mm"] <= TOL_MISMATCH)
    report.add(f"signal_lframe_rel_max_{tag}", worst["l_rel"], TOL_REL_MAX, worst["l_rel"] <= TOL_REL_MAX)
    # Even for the heaviest sources (SNR near 1e-4 Hz) a 150 s shift is ~0.1 rad,
    # far above round-off; this only guards against the shift being dropped.
    report.add(f"shift_applied_min_mismatch_{tag}", min_shift_mismatch, 1e-6, min_shift_mismatch >= 1e-6)


def check_train_path(report, inj, metadata, draws, frozen, rng):
    """SampleExtrinsicParameters (DeltatL + psi free) -> ProjectOntoSpaceDetectors."""
    import lisabeta.tools.pytools as pytools
    from dingo.gw.lisa_time import strip_time_shift_for_generator
    from dingo.gw.prior import BBHExtrinsicPriorDict, split_off_extrinsic_parameters
    from dingo.gw.transforms import ProjectOntoSpaceDetectors, SampleExtrinsicParameters
    from dingo.gw.gwutils import get_extrinsic_prior_dict

    tag = "frozen" if frozen else "moving"
    data = metadata["train_settings"]["data"]
    ext = dict(data["extrinsic_prior"])
    ext["DeltatL"] = "bilby.core.prior.Uniform(minimum=-150.0, maximum=150.0)"
    ext["psi"] = 'bilby.core.prior.Uniform(minimum=0.0, maximum=np.pi, boundary="periodic")'
    prior_dict = get_extrinsic_prior_dict(ext)
    sampler = SampleExtrinsicParameters(prior_dict)

    mean, std = BBHExtrinsicPriorDict(prior_dict).mean_std(["DeltatL", "psi"])
    ok = (abs(mean["DeltatL"]) < 1e-12 and abs(std["DeltatL"] - 300 / np.sqrt(12)) < 1e-9
          and abs(mean["psi"] - np.pi / 2) < 1e-12)
    report.add(f"standardization_DeltatL_psi_{tag}", 0.0 if ok else 1.0, 0.0, ok,
               mean_DeltatL=mean["DeltatL"], std_DeltatL=std["DeltatL"])

    lisa_settings = dict(data["lisa_settings"], frozenLISA=frozen)
    proj = ProjectOntoSpaceDetectors("TDIAET", inj.data_domain, data["ref_time"],
                                     data["detectors"], lisa_settings)
    min_idx = inj.data_domain.min_idx
    worst_mm = 0.0
    params_ok = True
    for theta in draws:
        # Modes generated at Deltat = 0, the way the training dataset holds them.
        # The generator also needs inc/sky/psi/dist for its frequency bounds.
        ti, te = split_off_extrinsic_parameters(dict(theta, Deltat=0.0))
        ti = {k: float(v) for k, v in ti.items()}
        ti = pytools.complete_mass_params(ti)
        ti = pytools.complete_spin_params(ti)
        wf_params = strip_time_shift_for_generator({**te, **ti})
        pols = inj.waveform_generator.generate_amp_phase(dict(wf_params))
        # Extrinsic values (distance, sky, psi, time, DeltatL) come from the prior
        # sampler, as in training; parameters hold the generation values.
        sample = sampler({"parameters": dict(wf_params), "waveform": pols})
        e = sample["extrinsic_parameters"]
        out = proj(sample)
        p = out["parameters"]
        params_ok &= ("DeltatL" in p and "Deltat" in p and abs(p["DeltatL"] - e["DeltatL"]) < 1e-12)
        # The same signal through Injection.signal (whitening is not part of `proj`).
        inj.whiten = False
        theta_e = dict(theta, Deltat=0.0, DeltatL=float(e["DeltatL"]), psi=float(e["psi"]),
                       dist=float(e["dist"]), **{"lambda": float(e["lambda"]), "beta": float(e["beta"])})
        if "geocent_time" in e:
            theta_e["geocent_time"] = float(e["geocent_time"])
        ref = inj.signal(theta_e)["waveform"]
        inj.whiten = True
        mm, _ = whitened_metrics(out["waveform"], ref, min_idx)
        worst_mm = max(worst_mm, abs(mm))
    report.add(f"train_path_params_{tag}", 0.0 if params_ok else 1.0, 0.0, params_ok)
    report.add(f"train_path_vs_signal_mismatch_{tag}", worst_mm, TOL_MISMATCH, worst_mm <= TOL_MISMATCH)


def main(argv=None):
    args = build_parser().parse_args(argv)
    t_start = time.time()
    rng = np.random.default_rng(args.seed)
    np.random.seed(args.seed % 2**32)  # bilby priors sample with np.random

    import torch
    from dingo.gw.noise.asd_dataset import ASDDataset

    sys.path.insert(0, args.injection_script_dir)
    import lisa_injection_inference as lii  # prior draw + naming adapters

    prov = provenance()
    print("Provenance:", json.dumps(prov, indent=2), flush=True)
    try:
        from dingo.gw import lisa_time  # noqa: F401
    except ImportError:
        raise SystemExit("This DINGO checkout has no dingo.gw.lisa_time; use branch claude/lisa-free-time.")

    ckpt = torch.load(args.model, map_location="cpu", weights_only=False)
    metadata = ckpt["metadata"]
    data = metadata["train_settings"]["data"]
    lisa_settings = data["lisa_settings"]
    t0_s = None

    asd_dataset = ASDDataset(file_name=metadata["train_settings"]["training"]["stage_0"]["asd_dataset_path"])
    asd = {k: v[args.asd_index] for k, v in asd_dataset.asds.items()}

    report = Report()
    check_constants(report)

    inj_model = make_injection(metadata, asd, bool(lisa_settings.get("frozenLISA", False)))
    draws = [lii.draw_injection(inj_model.prior, {}) for _ in range(args.n_draws)]
    t0_s = draws[0]["geocent_time"]
    print(f"t0_s (geocent_time) = {t0_s}", flush=True)

    check_conversions(report, rng, t0_s, lisa_settings["LISAconst"])
    check_response_delay(report, rng, t0_s, lisa_settings)

    shifts = [float(s) for s in args.shifts.split(",")]
    for frozen in (False, True):
        inj = make_injection(metadata, asd, frozen)
        check_signals(report, inj, draws, shifts, frozen)
        check_train_path(report, inj, metadata, draws[: min(3, len(draws))], frozen, rng)

    os.makedirs(args.outdir, exist_ok=True)
    job = os.environ.get("SLURM_JOB_ID", time.strftime("%Y%m%d_%H%M%S"))
    out = os.path.join(args.outdir, f"lisa_time_shift_validation_{job}.json")
    result = {
        "all_passed": report.all_passed,
        "checks": report.checks,
        "provenance": prov,
        "model": os.path.abspath(args.model),
        "lisa_settings": lisa_settings,
        "shifts": shifts,
        "n_draws": args.n_draws,
        "seed": args.seed,
        "draws": draws,
        "wall_time_s": time.time() - t_start,
    }
    with open(out, "w") as f:
        json.dump(result, f, indent=2, default=lambda o: o.tolist() if hasattr(o, "tolist") else str(o))
    n_fail = sum(not c["passed"] for c in report.checks)
    print(f"\n{'ALL PASSED' if report.all_passed else f'{n_fail} CHECK(S) FAILED'} "
          f"({len(report.checks)} checks, {time.time() - t_start:.0f} s). Report: {out}")
    return 0 if report.all_passed else 1


if __name__ == "__main__":
    sys.exit(main())
