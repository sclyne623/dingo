#!/usr/bin/env python3
"""
Cluster validation of the LISA coalescence-time shift (DINGO branch
claude/lisa-free-time). Needs lisabeta, so run it on Unity, not locally.

What it checks (all pass/fail, written to a JSON report):

1. constants        dingo.gw.lisa_time constants == lisabeta.pyconstants.
2. conversions      Deltat <-> DeltatL against lisabeta.lisa.lisatools
                    (tLfromSSBframe exactly, tSSBfromLframe to its own
                    second-order accuracy), and an exact round trip, for a moving
                    and a frozen LISA.
3. response_delay   Independent of lisatools: lisabeta's own response gives
                    phaseRdelay = 2 pi f x (delay SSB -> LISA). So
                    Deltat + phaseRdelay / (2 pi f) must equal our DeltatL. A sign
                    error would show up as ~2 x 500 s.
4. signal_ssb       Injection.signal with an extrinsic Deltat (modes generated at
                    Deltat = 0, shift applied in ProjectOntoSpaceDetectors) vs the
                    old path (modes generated by lisabeta with Deltat baked in, no
                    projection shift). Whitened mismatch must be at round-off level.
5. signal_lframe    Same with DeltatL, against the old path at the converted Deltat.
6. shift_applied    Sanity: the shifted signal really differs from the unshifted one.
7. train_path       The training transforms (SampleExtrinsicParameters with a
                    DeltatL + free psi prior, then ProjectOntoSpaceDetectors)
                    reproduce Injection.signal for the sampled values, and the
                    prior gives analytic standardizations for DeltatL and psi.

Checks 4-7 run for frozenLISA = False and True.

Usage (see lisa_time_shift_validation.sh):
    python lisa_time_shift_validation.py [--model ...] [--n-draws 6]
"""

from __future__ import annotations

